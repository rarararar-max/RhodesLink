    private val proactivePrivate = setOf(
        "PROACTIVE_TRIGGER_TYPE", "PROACTIVE_TRIGGER_CONTEXT", "PROACTIVE_CURRENT_TIME",
        "PROACTIVE_CONTEXT_MODE", "PROACTIVE_TIME_RELATION", "PROACTIVE_IDLE_DURATION",
        "PROACTIVE_LAST_INTERACTION_TIME", "PROACTIVE_LAST_USER_MESSAGE", "PROACTIVE_LAST_USER_TIME",
        "PROACTIVE_LAST_AI_MESSAGE", "PROACTIVE_LAST_AI_TIME", "PROACTIVE_UNRESOLVED_TOPIC",
        "PROACTIVE_RECENT_HISTORY"
