        "OUTPUT_FORMAT", "LONG_TERM_IMPRESSION", "SHORT_TERM_SUMMARY", "DAILY_SUMMARY",
        "GROUP_CONTEXT", "USER_RELATION", "SHARED_MEMORIES", "MEMORY_ANCHORS", "MEMORY_V2_CONTEXT",
        "SOURCE_AWARE_MEMORIES", "SOURCE_AWARE_RULES", "KNOWN_FROM_CONTEXT", "RECENT_SOCIAL_CONTEXT", "__KNOWLEDGE_BASE_CONTEXT",
        "GROUP_NAR_SEG_MIN", "GROUP_NAR_SEG_MAX",
