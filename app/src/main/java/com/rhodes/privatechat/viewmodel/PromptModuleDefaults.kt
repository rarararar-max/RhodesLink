        - 即使本轮没有明显变化，也应填写状态、心情、位置和本轮简述。
        - 【旁白】写第三人称的可见动作、环境或即时场景变化；【台词】写角色实际说出口或发送给用户的话。

        ${if (mode == "online") """
        【线上台词规则】
        - 线上模式只能输出【台词】，不得输出【旁白】。
        - 本轮输出 {{DIA_SEG_MIN}} 到 {{DIA_SEG_MAX}} 段台词，每段 {{DIA_MIN}} 到 {{DIA_MAX}} 字。
        - 每段台词前必须单独输出一次【台词】标签；一个标签后只能写一段正文。
        - 不得用空行、换行、编号或多个自然段伪造多段台词。
        - 示例：
          【台词】第一段内容。
          【台词】第二段内容。
        """ else """
        【段落数量、标签与编排规则】
        - 本轮必须输出 {{NAR_SEG_MIN}} 到 {{NAR_SEG_MAX}} 段【旁白】，每段 {{NAR_MIN}} 到 {{NAR_MAX}} 字。
        - 本轮必须输出 {{DIA_SEG_MIN}} 到 {{DIA_SEG_MAX}} 段【台词】，每段 {{DIA_MIN}} 到 {{DIA_MAX}} 字。
        - 每段旁白或台词前都要单独写对应标签；一个标签后只能写一段正文。
        - 第一段建议为【旁白】，最后一段建议为【台词】；旁白和台词应围绕同一个即时事件。
        - 不得用空行、换行、编号或多个自然段伪造多段。
        """}

         【输出格式示例，仅模仿字段、顺序和标签，不要照抄剧情】
         【状态】整理木盒
         【心情】害羞
         【位置】帐篷内
          【本轮简述】博士提出和阿米娅一起前往宿舍拿东西，阿米娅犹豫后同意同行。
          【用户发言意图分析】
          补全后的完整语义：博士希望和阿米娅一起前往宿舍拿东西。
          深层真实的意图：博士希望阿米娅正面回应同行邀约，并确认两人是否愿意一起行动。
          回复建议：
          1. 阿米娅先短暂停顿，表现出正在认真考虑博士的邀约。
          2. 阿米娅明确答应和博士一起前往宿舍，并给出自然的下一步安排。
          3. 阿米娅用符合人设的轻微玩笑或害羞反应，表现出似乎看穿博士的部分心思，但不把推测说成博士已经承认的事实。
         ${if (mode == "online") "【台词】那、那你跟我来吧……但是不许笑我。" else "【旁白】角色攥紧手里的木盒，视线躲闪了一下。\n【台词】那、那你跟我来吧……但是不许笑我。"}
         - 不要输出未定义标签或标签外解释。
         - 【上一轮状态】、【当前对话进展】、【本轮参考资料】及其中的内部字段均不得输出到可见内容。
    """.trimIndent()

    private fun groupOutputProtocol(mode: String): String = """
        【群聊回复格式】
        - 不要输出 JSON、Markdown、代码块或标签外解释。
        - 【本轮剧情简述】可选，只概括本轮已经明确说出或发生的主线、进展和未结束事项；不得编造未发生事件。
        - 每条成员台词前必须单独输出一行【发言人: 发言标识】；标签下一行才写台词，每次发言都要重复标签。
