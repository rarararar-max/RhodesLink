    private val group = setOf(
        "CURRENT_TIME", "CURRENT_DATE", "GROUP_NAME", "GROUP_INJECTION", "RELATION_HINTS",
        "GROUP_RELATION_HINTS", "GROUP_SUMMARY", "GROUP_RULES", "USER_NAME", "USER_GENDER",
