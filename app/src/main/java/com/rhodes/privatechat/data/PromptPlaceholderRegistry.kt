    fun allowed(type: String, mode: String = ""): Set<String> = when (type) {
        "private" -> if (mode == "proactive") private + proactivePrivate else private
        "group" -> group
        "moment" -> moment
        "moment_comment" -> comment
        "diary" -> diary
        "dispatch" -> dispatch
        else -> emptySet()
    }

    /** Fields used by shipped templates and guaranteed to receive meaningful runtime content. */
    fun recommended(type: String, mode: String = ""): Set<String> = when (type) {
        "private" -> buildSet {
            addAll(setOf(
                "OPERATOR_NAME", "OPERATOR_TITLE", "OPERATOR_PERSONA", "OPERATOR_GENDER",
                "USER_NAME", "USER_GENDER", "USER_BIO", "CURRENT_TIME", "PRIVATE_CONTINUITY_STATE",
                "HYPNOSIS", "TRANSITION_NOTICE", "LONG_TERM_IMPRESSION", "PERSONAL_MEMORY_REFERENCE_STYLE",
                "MEMORY_V2_CONTEXT", "SOURCE_AWARE_RULES", "SHORT_TERM_SUMMARY", "GROUP_CONTEXT",
                "USER_RELATION", "__KNOWLEDGE_BASE_CONTEXT", "NAR_SEG_MIN", "NAR_SEG_MAX", "NAR_MIN", "NAR_MAX",
                "DIA_SEG_MIN", "DIA_SEG_MAX", "DIA_MIN", "DIA_MAX"
            ))
            if (mode == "proactive") addAll(proactivePrivate)
        }
        "group" -> setOf(
            "CURRENT_TIME", "GROUP_NAME", "GROUP_RULES", "USER_NAME", "USER_GENDER", "USER_BIO",
            "USER_MESSAGE", "USER_OBSERVING", "MEMBER_NAMES", "MEMBER_PROFILES", "RELATION_HINTS",
            "MEMBER_PRIVATE_CONTEXT", "SHORT_TERM_SUMMARY", "DAILY_SUMMARY", "MEMORY_ANCHORS", "__KNOWLEDGE_BASE_CONTEXT",
            "RECENT_SOCIAL_CONTEXT", "SOURCE_AWARE_MEMORIES", "SOURCE_AWARE_RULES", "AUTO_REASON",
            "AUTO_REASON_TEXT", "GROUP_MODE_FORMAT", "GROUP_PLOT_SUMMARY", "GROUP_NAR_SEG_MIN", "GROUP_NAR_SEG_MAX",
            "GROUP_NAR_MIN", "GROUP_NAR_MAX", "GROUP_MSG_MIN", "GROUP_MSG_MAX", "GROUP_SPEECH_MIN", "GROUP_SPEECH_MAX"
        )
        else -> allowed(type, mode)
    }

    /** Values that can vary between requests and therefore belong outside a cacheable prompt prefix. */
    fun runtimeKeys(type: String, mode: String = ""): Set<String> {
        val stable = when (type) {
            "private" -> setOf(
                "OPERATOR_NAME", "OPERATOR_TITLE", "OPERATOR_PERSONA", "OPERATOR_GENDER",
                "NAR_SEG_MIN", "NAR_SEG_MAX", "NAR_MIN", "NAR_MAX", "DIA_SEG_MIN", "DIA_SEG_MAX",
                "DIA_MIN", "DIA_MAX", "SEG_MIN", "SEG_MAX", "PERSONAL_MEMORY_REFERENCE_STYLE",
                "SOURCE_AWARE_RULES", "MODE_RULES", "OUTPUT_FORMAT"
            )
            "group" -> setOf(
                "GROUP_NAME", "GROUP_MODE_FORMAT", "GROUP_NAR_SEG_MIN", "GROUP_NAR_SEG_MAX",
                "GROUP_NAR_MIN", "GROUP_NAR_MAX", "GROUP_MSG_MIN", "GROUP_MSG_MAX",
                "GROUP_SPEECH_MIN", "GROUP_SPEECH_MAX", "SOURCE_AWARE_RULES", "OUTPUT_FORMAT"
            )
            "moment" -> setOf(
                "OPERATOR_NAME", "OPERATOR_PERSONA", "OPERATOR_GENDER", "MOMENT_MIN_CHARS", "MOMENT_MAX_CHARS"
            )
            "moment_comment" -> setOf(
                "COMMENTER_NAME", "COMMENTER_GENDER", "COMMENTER_PERSONA", "POST_AUTHOR_NAME", "POST_AUTHOR_PERSONA",
                "COMMENT_MIN_CHARS", "COMMENT_MAX_CHARS"
            )
            "diary" -> setOf(
                "OPERATOR_NAME", "OPERATOR_PERSONA", "OPERATOR_GENDER", "DIARY_MIN_CHARS", "DIARY_MAX_CHARS"
            )
            else -> emptySet()
        }
        return allowed(type, mode) - stable
    }
}
